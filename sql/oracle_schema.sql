-- Schema Oracle da CLYVO VET (gerado a partir de app/db/models.py)
-- Prefixo CV_ evita colisão com TB_* do ProntPet/outras matérias no mesmo schema.

CREATE TABLE "CV_CLINICA" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	nome VARCHAR2(150 CHAR) NOT NULL, 
	PRIMARY KEY (id)
);

CREATE TABLE "CV_TUTOR" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	nome VARCHAR2(150 CHAR) NOT NULL, 
	email VARCHAR2(150 CHAR), 
	PRIMARY KEY (id)
);

CREATE TABLE "CV_PET" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	tutor_id INTEGER NOT NULL, 
	nome VARCHAR2(100 CHAR) NOT NULL, 
	especie VARCHAR2(20 CHAR) NOT NULL, 
	raca VARCHAR2(100 CHAR), 
	data_nascimento DATE NOT NULL, 
	sexo VARCHAR2(10 CHAR) NOT NULL, 
	tipo_sanguineo VARCHAR2(20 CHAR) NOT NULL, 
	castrado SMALLINT NOT NULL, 
	alergia VARCHAR2(255 CHAR), 
	doenca_cronica VARCHAR2(255 CHAR), 
	PRIMARY KEY (id), 
	CONSTRAINT ck_cv_pet_castrado CHECK (castrado IN (0, 1)), 
	FOREIGN KEY(tutor_id) REFERENCES "CV_TUTOR" (id)
);

CREATE TABLE "CV_CONSULTA" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	pet_id INTEGER NOT NULL, 
	clinica_id INTEGER NOT NULL, 
	data_consulta DATE NOT NULL, 
	sintomas VARCHAR2(500 CHAR), 
	diagnostico VARCHAR2(500 CHAR), 
	peso_kg FLOAT NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(pet_id) REFERENCES "CV_PET" (id), 
	FOREIGN KEY(clinica_id) REFERENCES "CV_CLINICA" (id)
);

CREATE TABLE "CV_VACINA_APLICADA" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	pet_id INTEGER NOT NULL, 
	nome VARCHAR2(100 CHAR) NOT NULL, 
	data_aplicacao DATE NOT NULL, 
	data_validade DATE, 
	PRIMARY KEY (id), 
	FOREIGN KEY(pet_id) REFERENCES "CV_PET" (id)
);

CREATE TABLE "CV_PREDICAO_RISCO" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, 
	consulta_id INTEGER NOT NULL, 
	risco INTEGER NOT NULL, 
	probabilidade FLOAT NOT NULL, 
	recomendacao VARCHAR2(500 CHAR) NOT NULL, 
	modelo_versao VARCHAR2(50 CHAR) NOT NULL, 
	criado_em DATE DEFAULT CURRENT_TIMESTAMP NOT NULL, 
	PRIMARY KEY (id), 
	UNIQUE (consulta_id), 
	FOREIGN KEY(consulta_id) REFERENCES "CV_CONSULTA" (id)
);

